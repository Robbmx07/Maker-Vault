export function stlBinary() {
  const b = Buffer.alloc(84 + 50);
  b.writeUInt32LE(1, 80);
  const verts = [[0, 0, 0], [10, 0, 0], [0, 20, 5]];
  verts.forEach((v, i) => v.forEach((n, j) => b.writeFloatLE(n, 84 + 12 + i * 12 + j * 4)));
  return b;
}

