export async function startApp() {
  const dir = fs.mkdtempSync(path.join(os.tmpdir(), 'vault-test-'));
  const db = openDb(':memory:');
  const server = createApp(db, { dataDir: dir, config: { brand: { name: 'Test' } } });
  await new Promise((r) => server.listen(0, '127.0.0.1', r));
  const base = `http://127.0.0.1:${server.address().port}`;
  const api = async (method, url, body, headers = {}) => {
    const res = await fetch(base + url, {
      method, headers: { ...(body && !(body instanceof Buffer) ? { 'Content-Type': 'application/json' } : {}), ...headers },
      body: body instanceof Buffer ? body : body ? JSON.stringify(body) : undefined,
    });
    const type = res.headers.get('content-type') || '';
    const data = type.includes('json') ? await res.json() : Buffer.from(await res.arrayBuffer());
    return { status: res.status, data, res };
  };
  const close = () => { server.close(); fs.rmSync(dir, { recursive: true, force: true }); };
  return { api, base, dir, close };
}
